import React, { useMemo, useState } from 'react';
import { keepPreviousData, useQuery, useQueryClient } from '@tanstack/react-query';
import { Download, RefreshCw, Search, Trash2 } from 'lucide-react';
import { api, apiError } from '../../api.js';
import { Drawer, Empty, ErrorState, Loading, PageHeading, Pagination, StatusPill, useCurrentUser, useToast } from '../../components/common.jsx';
import { fmtBytes, fmtDate, fmtNumber } from '../../lib/format.js';
import { downloadReport, useReportCatalog } from './ReportsPage.jsx';
import { describeFilters } from './ReportConfigFields.jsx';

export default function ReportHistoryPage() {
  const catalog = useReportCatalog();
  const { user, can } = useCurrentUser();
  const { notify } = useToast();
  const client = useQueryClient();
  const [draftQ, setDraftQ] = useState('');
  const [filters, setFilters] = useState({ q: '', report_type: '', status: '', format: '', user_id: '' });
  const [page, setPage] = useState(1);
  const [size, setSize] = useState(25);
  const [selected, setSelected] = useState(null);
  const manage = catalog.data?.capabilities?.manage;

  const params = useMemo(() => ({ page, size, ...Object.fromEntries(Object.entries(filters).filter(([, value]) => value)) }), [filters, page, size]);
  const history = useQuery({
    queryKey: ['report-history', params],
    queryFn: () => api.get('/report-history', { params }).then((r) => r.data),
    placeholderData: keepPreviousData,
    // Poll while anything is still generating.
    refetchInterval: (query) => (query.state.data?.items?.some((item) => item.status === 'running') ? 5000 : false),
  });
  const users = useQuery({ queryKey: ['users'], queryFn: () => api.get('/users').then((r) => r.data), enabled: Boolean(manage && can('admin:users')) });
  const typeLabel = (key) => catalog.data?.types.find((item) => item.key === key)?.label || key;
  const setFilter = (key) => (event) => { setFilters({ ...filters, [key]: event.target.value }); setPage(1); };

  async function remove(record) {
    if (!window.confirm(`Delete "${record.name}" and its file? This cannot be undone.`)) return;
    try {
      await api.delete(`/report-history/${record.id}`);
      setSelected(null);
      client.invalidateQueries({ queryKey: ['report-history'] });
      notify('Report deleted');
    } catch (error) {
      notify(apiError(error), 'error');
    }
  }

  const download = (record) => downloadReport(record).catch((error) => notify(error.message, 'error'));
  const canDelete = (record) => can('reports:generate') && (record.generated_by === user?.id || manage);
  const rows = history.data?.items || [];

  return (
    <>
      <PageHeading title="Report History" eyebrow="OPERATIONS" description={manage ? 'All generated reports across users.' : 'Reports you have generated, manually or by schedule.'}>
        <button className="secondary" onClick={() => history.refetch()}><RefreshCw size={14} /> Refresh</button>
      </PageHeading>

      <div className="panel filter-panel">
        <div className="toolbar-row">
          <form className="query-input" onSubmit={(event) => { event.preventDefault(); setFilters({ ...filters, q: draftQ.trim() }); setPage(1); }}>
            <Search size={14} /><input value={draftQ} onChange={(event) => setDraftQ(event.target.value)} placeholder="Search report name… (Enter)" maxLength={200} />
          </form>
          <select className="compact-select" value={filters.report_type} onChange={setFilter('report_type')} aria-label="Report type">
            <option value="">All report types</option>
            {(catalog.data?.types || []).map((item) => <option key={item.key} value={item.key}>{item.label}</option>)}
          </select>
          <select className="compact-select" value={filters.status} onChange={setFilter('status')} aria-label="Status">
            <option value="">All statuses</option><option value="completed">Completed</option><option value="failed">Failed</option>
            <option value="running">Running</option><option value="expired">Expired</option>
          </select>
          <select className="compact-select" value={filters.format} onChange={setFilter('format')} aria-label="Format">
            <option value="">All formats</option><option value="pdf">PDF</option><option value="xlsx">Excel</option><option value="csv">CSV</option>
          </select>
          {users.data && (
            <select className="compact-select" value={filters.user_id} onChange={setFilter('user_id')} aria-label="Generated by">
              <option value="">All users</option>
              {users.data.map((item) => <option key={item.id} value={item.id}>{item.username}</option>)}
            </select>
          )}
        </div>
      </div>

      <div className="panel table-panel">
        <div className="table-scroll">
          <table>
            <thead><tr><th>Report</th><th>Type</th><th>Generated by</th><th>Generated</th><th>Period</th><th>Format</th><th>Status</th><th>Size</th><th /></tr></thead>
            <tbody>
              {history.isLoading ? <tr><td colSpan={9}><Loading /></td></tr>
                : history.error ? <tr><td colSpan={9}><ErrorState error={history.error} /></td></tr>
                  : rows.length ? rows.map((record) => (
                    <tr key={record.id} className="click-row" onClick={() => setSelected(record)}>
                      <td><b>{record.name || `Report #${record.id}`}</b><small className="cell-sub">#{record.id} · {record.source}</small></td>
                      <td>{typeLabel(record.report_type)}</td>
                      <td>{record.generated_by_username || 'system'}</td>
                      <td className="timestamp">{fmtDate(record.created_at)}</td>
                      <td className="timestamp">{record.start_date ? `${fmtDate(record.start_date, { dateStyle: 'short', timeStyle: 'short' })} → ${fmtDate(record.end_date, { dateStyle: 'short', timeStyle: 'short' })}` : '—'}</td>
                      <td>{String(record.format || '—').toUpperCase()}</td>
                      <td><StatusPill status={record.status} /></td>
                      <td>{fmtBytes(record.file_size)}</td>
                      <td className="row-actions" onClick={(event) => event.stopPropagation()}>
                        {record.downloadable && <button className="icon-button" onClick={() => download(record)} aria-label="Download"><Download size={13} /></button>}
                        {canDelete(record) && <button className="icon-button" onClick={() => remove(record)} aria-label="Delete"><Trash2 size={13} /></button>}
                      </td>
                    </tr>
                  )) : <tr><td colSpan={9}><Empty message="No reports match these filters." /></td></tr>}
            </tbody>
          </table>
        </div>
        <Pagination page={page} size={size} total={history.data?.total || 0} onPage={setPage} onSize={(value) => { setSize(value); setPage(1); }} />
      </div>

      {selected && (
        <Drawer title={selected.name || `Report #${selected.id}`} eyebrow={`REPORT #${selected.id}`} onClose={() => setSelected(null)}
          actions={<>
            {selected.downloadable && <button className="primary wide" onClick={() => download(selected)}><Download size={13} /> Download</button>}
            {canDelete(selected) && <button className="secondary wide" onClick={() => remove(selected)}><Trash2 size={13} /> Delete</button>}
          </>}>
          <div className="drawer-meta"><StatusPill status={selected.status} /></div>
          <div className="detail-sections"><section>
            {[
              ['Report type', typeLabel(selected.report_type)], ['Generated by', selected.generated_by_username || 'system'], ['Trigger', selected.source],
              ['Requested', fmtDate(selected.created_at)], ['Completed', fmtDate(selected.completed_at)],
              ['Period start', selected.start_date ? fmtDate(selected.start_date) : null], ['Period end', selected.end_date ? fmtDate(selected.end_date) : null],
              ['Format', String(selected.format).toUpperCase()], ['File', selected.file_name], ['Size', fmtBytes(selected.file_size)],
              ['Rows', selected.row_count != null ? fmtNumber(selected.row_count) : null], ['Filters', describeFilters(selected.filters)],
              ['Schedule', selected.schedule_id ? `#${selected.schedule_id}` : null],
            ].filter(([, value]) => value).map(([label, value]) => <div className="detail-row" key={label}><span>{label}</span><b>{value}</b></div>)}
          </section>
          {selected.error && <section><h4>Error</h4><ErrorState error={selected.error} title="Generation failed" hint="" /></section>}
          {selected.status === 'expired' && <p className="muted note-line">The file was removed by the retention policy.</p>}
          </div>
        </Drawer>
      )}
    </>
  );
}
