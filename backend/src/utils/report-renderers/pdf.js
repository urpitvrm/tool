import PDFDocument from 'pdfkit';
import { config } from '../../config/index.js';
import { describeFilters, describePeriod, formatCell, formatDate } from './format.js';

const COLORS = {
  ink: '#0f172a', muted: '#64748b', border: '#e2e8f0', zebra: '#f8fafc', header: '#1e293b', accent: '#20a383',
  critical: '#dc2626', high: '#ea580c', medium: '#ca8a04', low: '#16a34a',
};
const MARGIN = 36;
const ROW_HEIGHT = 15;

// The built-in PDF fonts only cover WinAnsi; map common typography and replace the rest.
const pdfText = (value) => String(value ?? '')
  .replace(/[–—]/g, '-').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/…/g, '...')
  .replace(/[^\x09\x0a\x0d\x20-\x7e\xa0-\xff]/g, '?');

function contentWidth(doc) {
  return doc.page.width - MARGIN * 2;
}

function ensureSpace(doc, height) {
  if (doc.y + height > doc.page.height - MARGIN - 24) {
    doc.addPage();
    return true;
  }
  return false;
}

function heading(doc, text) {
  ensureSpace(doc, 60);
  doc.moveDown(0.6);
  doc.font('Helvetica-Bold').fontSize(12).fillColor(COLORS.ink).text(pdfText(text), MARGIN, doc.y);
  doc.moveTo(MARGIN, doc.y + 2).lineTo(MARGIN + contentWidth(doc), doc.y + 2).lineWidth(0.5).strokeColor(COLORS.border).stroke();
  doc.moveDown(0.5);
}

function header(doc, document) {
  doc.rect(0, 0, doc.page.width, 78).fill(COLORS.header);
  doc.rect(0, 78, doc.page.width, 3).fill(COLORS.accent);
  doc.font('Helvetica').fontSize(8).fillColor('#94a3b8').text('SENTINEL SOC  /  SECURITY REPORT', MARGIN, 18);
  doc.font('Helvetica-Bold').fontSize(18).fillColor('#ffffff').text(pdfText(document.title), MARGIN, 30, { width: contentWidth(doc) });
  doc.font('Helvetica').fontSize(9).fillColor('#cbd5e1').text(pdfText(`${document.reportLabel}  |  ${describePeriod(document)}`), MARGIN, 56);
  doc.y = 96;
  const meta = [
    ['Generated', `${formatDate(document.generatedAt, document.timezone)} (${document.timezone})`],
    ['Generated by', document.generatedBy],
    ...describeFilters(document.filters),
  ];
  doc.fontSize(8.5);
  for (const [label, value] of meta) {
    doc.font('Helvetica-Bold').fillColor(COLORS.muted).text(`${pdfText(label)}: `, MARGIN, doc.y, { continued: true })
      .font('Helvetica').fillColor(COLORS.ink).text(pdfText(value));
  }
}

function kpis(doc, items) {
  if (!items.length) return;
  doc.moveDown(0.8);
  const gap = 8;
  const perRow = Math.min(items.length, 7);
  const width = (contentWidth(doc) - gap * (perRow - 1)) / perRow;
  for (let start = 0; start < items.length; start += perRow) {
    ensureSpace(doc, 56);
    const top = doc.y;
    items.slice(start, start + perRow).forEach((item, index) => {
      const x = MARGIN + index * (width + gap);
      doc.roundedRect(x, top, width, 48, 4).lineWidth(0.6).strokeColor(COLORS.border).stroke();
      doc.rect(x, top, 3, 48).fill(COLORS[item.tone] || COLORS.accent);
      doc.font('Helvetica').fontSize(7.5).fillColor(COLORS.muted).text(pdfText(item.label.toUpperCase()), x + 10, top + 8, { width: width - 14 });
      doc.font('Helvetica-Bold').fontSize(16).fillColor(COLORS.ink).text(Number(item.value || 0).toLocaleString('en-US'), x + 10, top + 22, { width: width - 14 });
    });
    doc.y = top + 56;
  }
}

function barChart(doc, rows, labelKey, valueKey) {
  const values = rows.map((row) => Number(row[valueKey]) || 0);
  const max = Math.max(...values, 1);
  const width = contentWidth(doc);

  if (rows.length > 12) {
    // Column chart for long series (e.g. timelines).
    const height = 110;
    ensureSpace(doc, height + 42);
    doc.font('Helvetica').fontSize(7).fillColor(COLORS.muted).text(`Peak: ${max.toLocaleString('en-US')}`, MARGIN, doc.y, { width, align: 'right' });
    const top = doc.y + 4;
    const barWidth = width / rows.length;
    values.forEach((value, index) => {
      const barHeight = (value / max) * height;
      doc.rect(MARGIN + index * barWidth + barWidth * 0.12, top + height - barHeight, Math.max(barWidth * 0.76, 0.5), barHeight).fill(COLORS.accent);
    });
    doc.moveTo(MARGIN, top + height).lineTo(MARGIN + width, top + height).lineWidth(0.5).strokeColor(COLORS.border).stroke();
    doc.font('Helvetica').fontSize(7).fillColor(COLORS.muted);
    doc.text(pdfText(formatCell(rows[0][labelKey], doc._reportTimezone)), MARGIN, top + height + 4);
    doc.text(pdfText(formatCell(rows.at(-1)[labelKey], doc._reportTimezone)), MARGIN, top + height + 4, { width, align: 'right' });
    doc.y = top + height + 18;
    return;
  }

  const labelWidth = 170;
  const barMax = width * 0.45;
  for (const [index, row] of rows.entries()) {
    ensureSpace(doc, 16);
    const top = doc.y;
    doc.font('Helvetica').fontSize(8).fillColor(COLORS.ink).text(pdfText(formatCell(row[labelKey], doc._reportTimezone)), MARGIN, top + 2, { width: labelWidth - 8, height: 10, ellipsis: true });
    const tone = COLORS[String(row[labelKey]).toLowerCase()] || COLORS.accent;
    doc.rect(MARGIN + labelWidth, top + 2, Math.max((values[index] / max) * barMax, 1), 9).fill(tone);
    doc.font('Helvetica').fontSize(8).fillColor(COLORS.muted).text(values[index].toLocaleString('en-US'), MARGIN + labelWidth + barMax + 8, top + 2);
    doc.y = top + 14;
  }
  doc.moveDown(0.4);
}

function table(doc, columns, rows, timezone) {
  const width = contentWidth(doc);
  const totalWeight = columns.reduce((sum, column) => sum + (column.weight || 1), 0);
  const widths = columns.map((column) => (width * (column.weight || 1)) / totalWeight);

  const drawHeader = () => {
    const top = doc.y;
    doc.rect(MARGIN, top, width, ROW_HEIGHT + 1).fill(COLORS.header);
    let x = MARGIN;
    doc.font('Helvetica-Bold').fontSize(7.5).fillColor('#ffffff');
    columns.forEach((column, index) => {
      doc.text(pdfText(column.label), x + 3, top + 4.5, { width: widths[index] - 6, height: 9, ellipsis: true });
      x += widths[index];
    });
    doc.y = top + ROW_HEIGHT + 1;
  };

  ensureSpace(doc, ROW_HEIGHT * 3);
  drawHeader();
  rows.forEach((row, rowIndex) => {
    if (ensureSpace(doc, ROW_HEIGHT)) drawHeader();
    const top = doc.y;
    if (rowIndex % 2) doc.rect(MARGIN, top, width, ROW_HEIGHT).fill(COLORS.zebra);
    let x = MARGIN;
    doc.font('Helvetica').fontSize(7.5).fillColor(COLORS.ink);
    columns.forEach((column, index) => {
      const value = row[column.key];
      const tone = column.key === 'severity' ? COLORS[String(value).toLowerCase()] : null;
      doc.fillColor(tone || COLORS.ink).text(pdfText(formatCell(value, timezone)), x + 3, top + 4, { width: widths[index] - 6, height: 9, ellipsis: true });
      x += widths[index];
    });
    doc.y = top + ROW_HEIGHT;
  });
  doc.moveTo(MARGIN, doc.y).lineTo(MARGIN + width, doc.y).lineWidth(0.5).strokeColor(COLORS.border).stroke();
  doc.moveDown(0.6);
}

function note(doc, text) {
  ensureSpace(doc, 20);
  doc.font('Helvetica-Oblique').fontSize(8).fillColor(COLORS.muted).text(pdfText(text), MARGIN, doc.y, { width: contentWidth(doc) });
  doc.moveDown(0.4);
}

function footer(doc, document) {
  const range = doc.bufferedPageRange();
  for (let index = range.start; index < range.start + range.count; index += 1) {
    doc.switchToPage(index);
    const bottom = doc.page.height - MARGIN + 8;
    // Writing inside the bottom margin would otherwise trigger an automatic page break.
    const savedMargin = doc.page.margins.bottom;
    doc.page.margins.bottom = 0;
    doc.font('Helvetica').fontSize(7).fillColor(COLORS.muted)
      .text(pdfText(`Sentinel SOC  |  ${document.reportLabel}  |  Confidential`), MARGIN, bottom, { width: contentWidth(doc) / 2, lineBreak: false })
      .text(`Page ${index + 1} of ${range.count}`, MARGIN, bottom, { width: contentWidth(doc), align: 'right', lineBreak: false });
    doc.page.margins.bottom = savedMargin;
  }
}

export function renderPdf(document) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: MARGIN, bufferPages: true, info: { Title: pdfText(document.title), Author: 'Sentinel SOC', Subject: document.reportLabel } });
    doc._reportTimezone = document.timezone;
    const chunks = [];
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    try {
      header(doc, document);
      kpis(doc, document.kpis);
      for (const message of document.notes) note(doc, message);

      for (const section of document.sections) {
        heading(doc, section.title);
        if (!section.rows.length) { note(doc, 'No matching data for this period.'); continue; }
        if (section.chart) barChart(doc, section.rows, section.labelKey, section.valueKey);
        // Long series are summarized by the chart; the full series is in the Excel export.
        if (!section.chart || section.rows.length <= 30) table(doc, section.columns, section.rows.slice(0, config.reports.pdfMaxRows), document.timezone);
      }

      if (document.details) {
        heading(doc, `${document.details.title} (${document.details.total.toLocaleString('en-US')} matching)`);
        const rows = document.details.rows.slice(0, config.reports.pdfMaxRows);
        if (!rows.length) note(doc, 'No matching records for this period.');
        else table(doc, document.details.columns, rows, document.timezone);
        if (document.details.rows.length > rows.length) {
          note(doc, `PDF shows the first ${rows.length.toLocaleString('en-US')} rows. Generate the Excel or CSV format for all ${document.details.rows.length.toLocaleString('en-US')} rows.`);
        }
      }
      footer(doc, document);
      doc.end();
    } catch (error) {
      reject(error);
    }
  });
}
