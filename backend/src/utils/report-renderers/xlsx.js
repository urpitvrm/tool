import ExcelJS from 'exceljs';
import { DateTime } from 'luxon';
import { describeFilters, describePeriod, formatDate, isIsoDate } from './format.js';

const HEADER_FILL = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1E293B' } };

/** Excel has no time zones: store the wall-clock time of the report's zone so it displays correctly. */
function excelDate(value, timezone) {
  const date = DateTime.fromISO(String(value), { setZone: true });
  if (!date.isValid) return value;
  const local = date.setZone(timezone);
  return new Date(Date.UTC(local.year, local.month - 1, local.day, local.hour, local.minute, local.second));
}

function cellValue(value, timezone) {
  if (value == null) return '';
  if (isIsoDate(value)) return excelDate(value, timezone);
  if (typeof value === 'object') return JSON.stringify(value);
  return value;
}

function uniqueSheetName(workbook, name) {
  const base = String(name).replace(/[[\]:*?/\\]/g, ' ').slice(0, 28).trim() || 'Sheet';
  let candidate = base;
  for (let index = 2; workbook.getWorksheet(candidate); index += 1) candidate = `${base} ${index}`;
  return candidate;
}

function addTableSheet(workbook, title, columns, rows, timezone) {
  const sheet = workbook.addWorksheet(uniqueSheetName(workbook, title), { views: [{ state: 'frozen', ySplit: 1 }] });
  sheet.columns = columns.map((column) => ({
    header: column.label, key: column.key, width: Math.max(10, Math.min(60, Math.round((column.weight || 1) * 14))),
  }));
  for (const row of rows) sheet.addRow(Object.fromEntries(columns.map((column) => [column.key, cellValue(row[column.key], timezone)])));
  const headerRow = sheet.getRow(1);
  headerRow.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  headerRow.fill = HEADER_FILL;
  headerRow.alignment = { vertical: 'middle' };
  sheet.eachRow((row, index) => {
    if (index === 1) return;
    row.eachCell((cell) => { if (cell.value instanceof Date) cell.numFmt = 'yyyy-mm-dd hh:mm:ss'; });
  });
  if (rows.length) sheet.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: columns.length } };
  return sheet;
}

export async function renderXlsx(document) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Sentinel SOC';
  workbook.created = new Date();
  workbook.title = document.title;

  const summary = workbook.addWorksheet('Summary');
  summary.columns = [{ width: 28 }, { width: 70 }];
  summary.addRow([document.title]).font = { bold: true, size: 16 };
  summary.addRow([]);
  const meta = [
    ['Report type', document.reportLabel],
    ['Period', describePeriod(document)],
    ['Generated', `${formatDate(document.generatedAt, document.timezone)} (${document.timezone})`],
    ['Generated by', document.generatedBy],
    ['Times shown in', document.timezone],
    ...describeFilters(document.filters),
  ];
  for (const [label, value] of meta) summary.addRow([label, value]).getCell(1).font = { bold: true };
  if (document.kpis.length) {
    summary.addRow([]);
    const head = summary.addRow(['Metric', 'Value']);
    head.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    head.fill = HEADER_FILL;
    for (const kpi of document.kpis) summary.addRow([kpi.label, Number(kpi.value || 0)]);
  }
  if (document.notes.length) {
    summary.addRow([]);
    for (const message of document.notes) summary.addRow(['Note', message]).getCell(1).font = { italic: true };
  }

  for (const section of document.sections) addTableSheet(workbook, section.title, section.columns, section.rows, document.timezone);
  if (document.details) addTableSheet(workbook, document.details.title, document.details.columns, document.details.rows, document.timezone);

  return Buffer.from(await workbook.xlsx.writeBuffer());
}
